-- 3. company_filter_options에 지역 매핑 삽입
-- ============================================

INSERT INTO company_filter_options (company_id, filter_option_id, created_at)
SELECT DISTINCT
    c.id,
    fo.id,
    NOW()
FROM companies c
JOIN company_location_mapping clm ON c.uuid = clm.company_uuid
CROSS JOIN LATERAL unnest(clm.location_shortname) AS loc(region_code)
JOIN region_name_mapping rnm ON rnm.tag_code = loc.region_code
JOIN filter_categories fc ON fc.code = 'region' AND fc.is_deleted = false
JOIN filter_options fo ON fo.category_id = fc.id AND fo.name = rnm.filter_name AND fo.is_deleted = false
WHERE c.is_deleted = false
AND NOT EXISTS (
    SELECT 1 FROM company_filter_options cfo
    WHERE cfo.company_id = c.id AND cfo.filter_option_id = fo.id
);

