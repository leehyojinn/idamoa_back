DO $$
DECLARE
    v_region_mappings INTEGER;
    v_companies_with_region INTEGER;
BEGIN
    SELECT COUNT(*) INTO v_region_mappings
    FROM company_filter_options cfo
    JOIN filter_options fo ON cfo.filter_option_id = fo.id
    JOIN filter_categories fc ON fo.category_id = fc.id
    WHERE fc.code = 'region';

    SELECT COUNT(DISTINCT cfo.company_id) INTO v_companies_with_region
    FROM company_filter_options cfo
    JOIN filter_options fo ON cfo.filter_option_id = fo.id
    JOIN filter_categories fc ON fo.category_id = fc.id
    WHERE fc.code = 'region';

    RAISE NOTICE '=== V55 Migration Complete ===';
    RAISE NOTICE 'Total region mappings: %', v_region_mappings;
    RAISE NOTICE 'Companies with region filters: %', v_companies_with_region;
END $$;

